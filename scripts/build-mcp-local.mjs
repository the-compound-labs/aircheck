#!/usr/bin/env node
/* Bundle src/server/local-api.ts into mcp/local-api.mjs, so the MCP server's bridge runs the very
 * code the local app serves at /api/runs: previews, Fix, revise, Replace and Undo, on this
 * machine, for aircheck.dev. Run before publishing aircheck-mcp (its prepublishOnly does). */
import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
await build({
  entryPoints: [path.join(root, 'src/server/local-api.ts')],
  outfile: path.join(root, 'mcp/local-api.mjs'),
  bundle: true, platform: 'node', format: 'esm', target: 'node20',
  tsconfig: path.join(root, 'tsconfig.json'),
  banner: { js: "// GENERATED by scripts/build-mcp-local.mjs from src/server/local-api.ts. Do not edit.\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  logLevel: 'warning',
});
console.log('built mcp/local-api.mjs');
